"""
Build the live status dashboard. Phase 11.

A single self-contained HTML page showing what the system currently says, from
the live database. Regenerated by daily.sh, so it is a snapshot that refreshes
rather than a served app — there is no web server on this VM and adding one to
show a page would be more moving parts than the page is worth.

The four verdicts lead the page deliberately. The interesting fact about this
system is not how much machinery it has, it is that the machinery keeps
answering no, and a dashboard that buried that under capability tiles would be
the green-dashboard failure the promotion policy already had to fix.
"""
