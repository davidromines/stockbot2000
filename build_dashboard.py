def gather(conn, cfg: dict) -> dict:
    def q(sql, default=0):
        try:
            v = conn.execute(sql).fetchone()
            return v[0] if v and v[0] is not None else default
        except Exception:      # noqa: BLE001 — a missing table is a zero, not a crash
            return default

    funds = []
    for r in conn.execute("""SELECT p.label, p.family, p.capital_usd, p.started_on,
        e.equity_usd, e.date FROM paper_runs p LEFT JOIN paper_equity e
        ON e.run_id=p.run_id AND e.date=(SELECT MAX(date) FROM paper_equity e2
        WHERE e2.run_id=p.run_id) WHERE p.status='open'"""):
        if r["equity_usd"] and r["capital_usd"]:
            funds.append({"name": r["label"], "family": r["family"],
                          "ret": r["equity_usd"] / r["capital_usd"] - 1,
                          "mark": r["date"]})
    for r in conn.execute("""SELECT f.label, f.capital_usd, e.equity_usd, e.date
        FROM pair_funds f LEFT JOIN pair_fund_equity e ON e.name=f.name
        AND e.date=(SELECT MAX(date) FROM pair_fund_equity e2 WHERE e2.name=f.name)
        WHERE f.status='open'"""):
        if r["equity_usd"] and r["capital_usd"]:
            funds.append({"name": r["label"], "family": "pair",
                          "ret": r["equity_usd"] / r["capital_usd"] - 1,
                          "mark": r["date"]})
    funds.sort(key=lambda f: -f["ret"])

    lib = {r[0]: r[1] for r in conn.execute(
        "SELECT validation_status, COUNT(*) FROM strategy_library "
        "GROUP BY validation_status")} if q(
        "SELECT COUNT(*) FROM sqlite_master WHERE name='strategy_library'") else {}

    n_ctrl = q("SELECT COUNT(*) FROM random_control")
    return {
        "generated": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "prices": q("SELECT COUNT(*) FROM prices"),
        "price_max": q("SELECT MAX(date) FROM prices", ""),
        "tickers": q("SELECT COUNT(DISTINCT ticker) FROM prices"),
        "features": q("SELECT COUNT(*) FROM features"),
        "fundamentals": q("SELECT COUNT(*) FROM daily_fundamentals"),
        "sec_facts": q("SELECT COUNT(*) FROM sec_facts"),
        "evaluations": q("SELECT COUNT(*) FROM evaluations"),
        "strategies": q("SELECT COUNT(*) FROM strategies"),
        "league": q("SELECT COUNT(DISTINCT strategy_key) FROM league_strategies"),
        "rankable": q("SELECT COUNT(*) FROM scoreboard_snapshots WHERE rankable=1"),
        "control_n": n_ctrl,
        "control_passed": q("SELECT COALESCE(SUM(passed_gate),0) FROM random_control"),
        "control_sharpe": q("SELECT MAX(sharpe) FROM random_control", 0.0),
        "control_pnl": q("SELECT MAX(net_pnl_usd) FROM random_control", 0.0),
        "library": lib, "funds": funds,
        "search_mode": (cfg.get("search") or {}).get("mode", "ACTIVE"),
        "min_marks": (cfg.get("league") or {}).get("min_rank_marks", 60),
    }


def render(d: dict) -> str:
    def n(x):
        return f"{x:,}"

    fund_rows = []
    for f in d["funds"]:
        cls = "up" if f["ret"] > 0 else ("flat" if f["ret"] == 0 else "down")
        # Bar width is proportional to |return| against the largest move, so the
        # eye reads magnitude rather than sign alone.
        mx = max((abs(x["ret"]) for x in d["funds"]), default=1) or 1
        w = abs(f["ret"]) / mx * 100
        fund_rows.append(
            f'<tr><td class="nm">{html.escape(f["name"])}</td>'
            f'<td><span class="fam">{html.escape(f["family"] or "—")}</span></td>'
            f'<td class="num {cls}">{f["ret"]*100:+.2f}%</td>'
            f'<td class="barcell"><span class="bar {cls}" style="width:{w:.1f}%"></span></td>'
            f'</tr>')

    lib = d["library"]
    lib_rows = "".join(
        f'<div class="librow"><span class="libk {k.lower()}">{k}</span>'
        f'<span class="libv">{v}</span></div>'
        for k, v in sorted(lib.items(), key=lambda kv: -kv[1]))

